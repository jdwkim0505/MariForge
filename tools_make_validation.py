"""Build every character at the default request, verify the exported geometry,
and write VALIDATION.md (and the README table) from the real numbers."""
from __future__ import annotations

import re
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from backend.cad.hull import build_parts        # noqa: E402
from backend.cad.verify import verify_design    # noqa: E402
from backend.physics.variants import generate_variants  # noqa: E402

REQ = {"length_mm": 800, "beam_mm": 250, "height_mm": 260,
       "cruise_speed_mps": 0.9, "endurance_min": 30, "bed_mm": 250}


def main() -> None:
    rows = []
    for d in generate_variants(REQ):
        t = time.time()
        parts = build_parts(d)
        v = verify_design(d, parts)
        dt = time.time() - t
        cuts_ok = sum(c["ok"] for c in v["cuts"])
        real = sum(v["printed_mass_g"].values())
        rows.append(
            f"| {d['label']} | {d['hydrostatics']['displacement_g']:.0f} g "
            f"| {100 * v['volume_error']:+.2f} % | {v['mesh_hydrostatics']['float_z_mm']:+.2f} mm "
            f"| {v['mesh_hydrostatics']['lcb_minus_lcg_mm']:+.1f} mm "
            f"| {cuts_ok}/{len(v['cuts'])} "
            f"| {'yes' if v['hull_valid'] and v['hull_solids'] == 1 and v['hull_mesh_watertight'] else 'NO'} "
            f"| {real:.0f} g vs {v['printed_mass_physics_g']:.0f} g "
            f"| {dt:.0f} s |")
        print(rows[-1], flush=True)
    head = ("| Hull | Design displacement | STL volume at DWL vs design | Floats at (DWL = 0) "
            "| LCB − LCG | Cuts verified | One valid watertight solid | Printed mass: CAD vs estimate "
            "| Build + verify |\n|---|---|---|---|---|---|---|---|---|")
    table = head + "\n" + "\n".join(rows)
    req = ", ".join(f"{k} {v}" for k, v in REQ.items())
    Path("VALIDATION.md").write_text(
        "# Validation\n\nGenerated by `tools_make_validation.py` from real builds "
        f"({time.strftime('%Y-%m-%d')}), request: {req}.\n\n{table}\n\n"
        "Volume and float height come from slicing the exported hydrostatic envelope STL "
        "(trimesh, capped) at the waterline; the float height is the waterline at which "
        "that mesh displaces the design mass. Cuts are point classifications of the "
        "finished hull solid at the centre of every bore, pocket, groove and the cavity.\n")
    readme = Path("README.md")
    text = readme.read_text()
    block = f"<!-- validation:start -->\n{table}\n<!-- validation:end -->"
    if "VALIDATION_TABLE" in text:
        text = text.replace("VALIDATION_TABLE", block)
    else:
        text = re.sub(r"<!-- validation:start -->.*?<!-- validation:end -->", block, text, flags=re.S)
    readme.write_text(text)


if __name__ == "__main__":
    main()
